#!/usr/bin/env node
/**
 * Generate `public/_redirects` from `shared/retired-urls.json`.
 *
 * Netlify reads `_redirects` from the publish directory. Keeping the list in one
 * JSON file means Nuxt `routeRules` (dev/preview) and the production 301s cannot
 * drift apart. Runs automatically before `pnpm build`.
 *
 * Fails when the map would create a redirect chain or points at a page that has
 * no content file — both were audit findings (P0-1, P0-2).
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'

const root = process.cwd()
const { redirects } = JSON.parse(readFileSync(resolve(root, 'shared/retired-urls.json'), 'utf8'))

const problems = []
const targets = new Set(Object.values(redirects))

for (const [from, to] of Object.entries(redirects)) {
  if (targets.has(from))
    problems.push(`redirect chain: ${from} is both a source and a target (→ ${to})`)
  if (from === to)
    problems.push(`self redirect: ${from}`)

  // A target must be a real content page: `/path` → content/es/path.md (or path/index.md)
  const isEn = to === '/en' || to.startsWith('/en/')
  const locale = isEn ? 'en' : 'es'
  const rel = to === '/' || to === '/en'
    ? ''
    : (isEn ? to.replace(/^\/en\//, '') : to).replace(/^\//, '')
  const candidates = rel === ''
    ? ['index.md']
    : [`${rel}.md`, `${rel}/index.md`]
  if (!candidates.some(c => existsSync(resolve(root, 'content', locale, c))))
    problems.push(`target has no content file: ${to} (expected content/${locale}/${candidates[0]})`)
}

if (problems.length) {
  console.error(`✖ ${problems.length} problem(s) in shared/retired-urls.json`)
  for (const p of problems) console.error(`  - ${p}`)
  process.exit(1)
}

const lines = [
  '# Generated by scripts/generate-redirects.mjs from shared/retired-urls.json — do not edit by hand.',
  '# `!` forces the rule so a stale prerendered file can never shadow the 301.',
  '',
  ...Object.entries(redirects).map(([from, to]) => `${from}  ${to}  301!`),
  '',
]

const out = resolve(root, 'public/_redirects')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, lines.join('\n'), 'utf8')
console.log(`✔ public/_redirects — ${Object.keys(redirects).length} one-hop 301s`)
